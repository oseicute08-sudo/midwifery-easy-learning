export function searchTerms(query) {
  if (!query || !query.trim()) return dictionaryTerms;
  const q = query.toLowerCase().trim();
  return dictionaryTerms.filter(
    (t) =>
      t.term.toLowerCase().includes(q) ||
      t.definition.toLowerCase().includes(q) ||
      t.category.toLowerCase().includes(q) ||
      (t.simpleExplanation && t.simpleExplanation.toLowerCase().includes(q))
  );
}

export function getTermById(id) {
  return dictionaryTerms.find((t) => t.id === id);
}

export function getTermsByLetter(letter) {
  return dictionaryTerms.filter((t) => t.term[0].toUpperCase() === letter.toUpperCase());
}

export function getAlphabet() {
  return 'ABCDEFGHIJKLMNOPQRSTUVWXYZ'.split('');
}
